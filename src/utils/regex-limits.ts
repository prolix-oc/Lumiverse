/**
 * Host-enforced limits for every untrusted regex operation.
 *
 * These values are deliberately expressed in UTF-8 bytes rather than JS
 * UTF-16 code units. Callers may choose stricter per-turn values, but an
 * imported script or preset must never raise a host ceiling.
 */
export const REGEX_LIMITS_V1 = Object.freeze({
  maxScripts: 512,
  maxPatterns: 1024,
  maxPatternBytes: 64 * 1024,
  maxReplacementBytes: 128 * 1024,
  maxActionBytes: 16 * 1024,
  maxActionCount: 50,
  maxTrimStrings: 512,
  maxTrimStringBytes: 512,
  maxMatchCount: 1024,
  maxInputBytes: 8 * 1024 * 1024,
  maxOutputBytes: 8 * 1024 * 1024,
  maxExpansionBytes: 16 * 1024 * 1024,
  maxOperationBytes: 2 * 1024 * 1024,
  maxCount: 10_000,
} as const);

const utf8Encoder = new TextEncoder();

export function utf8ByteLength(value: string): number {
  return utf8Encoder.encode(value).byteLength;
}

/** Truncate at a code-point boundary without producing invalid UTF-8. */
export function truncateUtf8(value: string, maxBytes: number): string {
  if (maxBytes <= 0 || value.length === 0) return "";
  if (utf8ByteLength(value) <= maxBytes) return value;
  let end = Math.min(value.length, maxBytes);
  while (end > 0) {
    const candidate = value.slice(0, end);
    if (utf8ByteLength(candidate) <= maxBytes) return candidate;
    end -= 1;
  }
  return "";
}

export type RegexValidationErrorCode =
  | "invalid_input"
  | "invalid_regex"
  | "invalid_flags"
  | "pattern_too_large"
  | "replacement_too_large"
  | "action_too_large"
  | "action_count_exceeded"
  | "trim_string_empty"
  | "trim_string_too_large"
  | "trim_string_invalid"
  | "trim_string_count_exceeded"
  | "script_count_exceeded"
  | "pattern_count_exceeded"
  | "match_limit_exceeded"
  | "output_limit_exceeded"
  | "expansion_limit_exceeded"
  | "operation_limit_exceeded"
  | "queue_full"
  | "zero_progress_transform"
  | "cancelled"
  | "deadline_exceeded"
  | "worker_unavailable"
  | "worker_crashed"
  | "worker_malformed"
  | "worker_timed_out";

