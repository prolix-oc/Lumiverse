export function isRegexValidationErrorCode(value: unknown): value is RegexValidationErrorCode {
  return typeof value === "string"
    && REGEX_VALIDATION_ERROR_CODES[value as RegexValidationErrorCode] === true;
}

export interface RegexValidationFailure {
  readonly code: RegexValidationErrorCode;
  readonly message: string;
}

export class RegexLimitError extends Error {
  constructor(
    public readonly code: RegexValidationErrorCode,
    message: string,
  ) {
    super(message);
    this.name = "RegexLimitError";
  }
}

export class RegexCancelledError extends Error {
  constructor(message = "Regex evaluation was cancelled") {
    super(message);
    this.name = "RegexCancelledError";
  }
}

export class RegexDeadlineError extends RegexLimitError {
  constructor(message = "Regex evaluation exceeded its deadline") {
    super("deadline_exceeded", message);
    this.name = "RegexDeadlineError";
  }
}

/**
 * Counts only bytes generated by replacements/macros, not unchanged source
 * slices. Every caller reserves before constructing a rebuilt output.
 */
export class RegexExpansionBudget {
  private usedBytes = 0;

  constructor(
    public readonly maxBytes = REGEX_LIMITS_V1.maxExpansionBytes,
  ) {}

  get consumedBytes(): number {
    return this.usedBytes;
  }

  remainingBytes(): number {
    return this.maxBytes - this.usedBytes;
  }

  reserve(bytes: number): void {
    if (!Number.isSafeInteger(bytes) || bytes < 0) {
      throw new RegexLimitError("invalid_input", "Invalid regex expansion byte count");
    }
    if (bytes > REGEX_LIMITS_V1.maxOperationBytes) {
      throw new RegexLimitError(
        "operation_limit_exceeded",
        `Regex operation generated more than ${REGEX_LIMITS_V1.maxOperationBytes} bytes`,
      );
    }
    if (this.usedBytes + bytes > this.maxBytes) {
      throw new RegexLimitError(
        "expansion_limit_exceeded",
        `Regex expansion exceeded ${this.maxBytes} bytes`,
      );
    }
    this.usedBytes += bytes;
  }
}

export function assertRegexTextBytes(
  value: string,
  maxBytes: number,
  code: RegexValidationErrorCode,
  label: string,
): void {
  const bytes = utf8ByteLength(value);
  if (bytes > maxBytes) {
    throw new RegexLimitError(code, `${label} exceeds maximum UTF-8 size of ${maxBytes} bytes`);
  }
}

export function throwIfRegexAborted(
  signal?: AbortSignal,
  deadlineAt?: number,
): void {
  if (signal?.aborted) throw new RegexCancelledError();
  if (deadlineAt !== undefined && Date.now() >= deadlineAt) throw new RegexDeadlineError();
}
